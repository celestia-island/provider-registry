def save_entrypoint_config(provider_id: str, entrypoint_file: str, config: Dict, config_dir: Path):
    """Save entrypoint config file"""
    config_path = get_entrypoint_path(provider_id, entrypoint_file, config_dir)
    config_path.parent.mkdir(parents=True, exist_ok=True)

    try:
        import toml  # type: ignore[import-untyped]

        with open(config_path, 'w', encoding='utf-8') as f:
            # Write entrypoint section
            if 'entrypoint' in config:
                ep = config['entrypoint']

                # Write header comment
                f.write(f"# {ep.get('name', {}).get('en', provider_id)}\n")
                if 'description' in ep:
                    f.write(f"# {ep['description']}\n")

                # Write [entrypoint] section
                f.write('\n[entrypoint]\n')
                for key, value in ep.items():
                    # Skip keys that are handled separately
                    if key in ['name', 'description', 'defaults', 'models']:
                        continue
                    if isinstance(value, str):
                        f.write(f'{key} = "{value}"\n')
                    elif isinstance(value, bool):
                        f.write(f'{key} = {str(value).lower()}\n')
                    elif isinstance(value, list):
                        f.write(f'{key} = [')
                        f.write(', '.join(f'"{v}"' for v in value))
                        f.write(']\n')
                    elif isinstance(value, dict):
                        f.write(f'\n[entrypoint.{key}]\n')
                        for sk, sv in value.items():
                            if isinstance(sv, str):
                                f.write(f'{sk} = "{sv}"\n')
                            elif isinstance(sv, bool):
                                f.write(f'{sk} = {str(sv).lower()}\n')
                            elif isinstance(sv, (int, float)):
                                f.write(f'{sk} = {sv}\n')
                    else:
                        f.write(f'{key} = {value}\n')

            # Write entrypoint.name section (8 languages)
            if 'entrypoint' in config and 'name' in config['entrypoint']:
                f.write('\n[entrypoint.name]\n')
                names = config['entrypoint']['name']
                for lang in ['en', 'zhs', 'zht', 'ja', 'ko', 'fr', 'es', 'ru']:
                    if lang in names:
                        f.write(f'{lang} = "{names[lang]}"\n')

            # Write entrypoint.defaults section
            if 'entrypoint' in config and 'defaults' in config['entrypoint']:
                f.write('\n[entrypoint.defaults]\n')
                defaults = config['entrypoint']['defaults']
                for tier in ['deep', 'normal', 'basic']:
                    if tier in defaults and defaults[tier] and isinstance(defaults[tier], str):
                        f.write(f'{tier} = "{defaults[tier]}"\n')
                # Write nested dicts (e.g., max_concurrent)
                for key, value in defaults.items():
                    if isinstance(value, dict):
                        f.write(f'\n[entrypoint.defaults.{key}]\n')
                        for sk, sv in value.items():
                            if isinstance(sv, str):
                                f.write(f'{sk} = "{sv}"\n')
                            elif isinstance(sv, bool):
                                f.write(f'{sk} = {str(sv).lower()}\n')
                            else:
                                f.write(f'{sk} = {sv}\n')

            # Write models
            if 'entrypoint' in config and 'models' in config['entrypoint']:
                for model in config['entrypoint']['models']:
                    f.write('\n[[entrypoint.models]]\n')
                    for key, value in model.items():
                        if key == 'pricing':
                            continue
                        if isinstance(value, str):
                            f.write(f'{key} = "{value}"\n')
                        elif isinstance(value, bool):
                            f.write(f'{key} = {str(value).lower()}\n')
                        elif isinstance(value, (int, float)):
                            f.write(f'{key} = {value}\n')
                        elif isinstance(value, list):
                            f.write(f'{key} = [')
                            f.write(', '.join(f'"{v}"' for v in value))
                            f.write(']\n')

                    # Write pricing
                    if 'pricing' in model:
                        f.write('\n[entrypoint.models.pricing]\n')
                        for pk, pv in model['pricing'].items():
                            if isinstance(pv, float):
                                f.write(f'{pk} = {pv}\n')
                            else:
                                f.write(f'{pk} = {pv}\n')

        cf.ok(f"Saved {provider_id}/{entrypoint_file}")
    except Exception as e:
        cf.err(f"Failed to save {provider_id}/{entrypoint_file}: {e}")


def save_config(provider_id: str, config: Dict, config_dir: Path):
    """Save config file, maintaining correct TOML order (provider first, models after)"""
    config_path = config_dir / f"{provider_id}.toml"

    try:
        import toml  # type: ignore[import-untyped]

        # Separate provider config and models
        provider_config = {k: v for k, v in config.items() if k != 'models'}
        models_list = config.get('models', [])

        with open(config_path, 'w', encoding='utf-8') as f:
            # Write provider config first
            if provider_config:
                toml.dump(provider_config, f)
                f.write('\n')

            # Write models last
            if models_list:
                for model in models_list:
                    # Write model as [[models]]
                    f.write('[[models]]\n')
                    model_copy = {k: v for k, v in model.items() if k != 'pricing'}
                    for key, value in model_copy.items():
                        if isinstance(value, str):
                            f.write(f'{key} = "{value}"\n')
                        elif isinstance(value, bool):
                            f.write(f'{key} = {str(value).lower()}\n')
                        elif isinstance(value, (int, float)):
                            f.write(f'{key} = {value}\n')
                        elif isinstance(value, list):
                            f.write(f'{key} = [')
                            f.write(', '.join(f'"{v}"' for v in value))
                            f.write(']\n')

                    # Write pricing
                    if 'pricing' in model:
                        f.write('\n[models.pricing]\n')
                        for pk, pv in model['pricing'].items():
                            if isinstance(pv, float):
                                f.write(f'{pk} = {pv}\n')
                            else:
                                f.write(f'{pk} = {pv}\n')

                    f.write('\n')

        cf.ok(f"Saved {provider_id}.toml")
    except Exception as e:
        cf.err(f"Failed to save {provider_id}.toml: {e}")


def save_individual_model_files(
    provider_id: str,
    models: List[ModelInfo],
    config_dir: Path,
) -> int:
    """Save individual TOML files for each model to the models/ directory"""
    models_dir = config_dir / "models" / provider_id
    models_dir.mkdir(parents=True, exist_ok=True)

    saved_count = 0
    written_canon = set()

    for model in models:
        # Canonical guard: two spellings of one model (e.g. MiniMax-M3 vs
        # minimax-m3) must not produce twin card files.
        c = canonical_id(model.id)
        if c in written_canon:
            continue
        written_canon.add(c)

        # Sanitize model ID for filename (replace / and other special chars)
        filename = model.id.replace('/', '_').replace(':', '-') + '.toml'
        model_path = models_dir / filename

        try:
            with open(model_path, 'w', encoding='utf-8') as f:
                # Write header comment
                f.write(f"# {model.name}\n")
                f.write(f"# Provider: {provider_id}\n")
                f.write(f"\n")

                # Write [model] section
                f.write("[model]\n")
                f.write(f'id = "{model.id}"\n')
                f.write(f'name = "{model.name}"\n')
                f.write(f'provider_id = "{provider_id}"\n')
                f.write(f'\n')

                # Write capabilities
                f.write(f"context_window = {model.context_window}\n")
                f.write(f"max_output_tokens = {model.max_output_tokens}\n")
                f.write(f"supports_vision = {str(model.supports_vision).lower()}\n")
                f.write(f"supports_function_calling = {str(model.supports_function_calling).lower()}\n")
                f.write(f"supports_streaming = {str(model.supports_streaming).lower()}\n")
                f.write(f"supports_reasoning = {str(model.supports_reasoning).lower()}\n")

                # Write tags
                if model.tags:
                    tags_str = '", "'.join(model.tags)
                    f.write(f'tags = ["{tags_str}"]\n')
                else:
                    f.write(f"tags = []\n")

                # Write pricing
                f.write(f"\n[model.pricing]\n")
                f.write(f"input_per_million = {model.pricing_input}\n")
                f.write(f"output_per_million = {model.pricing_output}\n")
                if model.pricing_cached > 0:
                    f.write(f"cached_per_million = {model.pricing_cached}\n")

                # Write capability score (when available)
                if model.score is not None:
                    f.write(f"\n[model.score]\n")
                    f.write(f"value = {model.score}\n")
                    src = model.score_source if model.score_source else 'manual'
                    f.write(f'source = "{src}"\n')

            saved_count += 1
        except Exception as e:
            cf.err(f"Failed to save model file {filename}: {e}")

    cf.ok(f"Saved {saved_count} model files for {provider_id}")
    return saved_count



def curate_entrypoint_blocks(
    new_blocks: List[Dict[str, Any]],
    existing_blocks: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Curation-first merge for an entrypoint's [[entrypoint.models]] blocks.

    For a model id already on disk the EXISTING block wins verbatim — the
    inline pricing of a standard entrypoint mirrors the hand-verified card
    (and in coding plans it IS the plan's charge multiplier, not a retail
    price), so a scheduled sync must never rewrite it. New ids are appended
    in the incoming order; ids present on disk but absent from the new list
    are retained (never dropped by a cap or a feed gap).

    Canonical-id dedup (audit 2026-10-21): a block whose id differs from an
    already-placed block only by case/separators (claude-opus-5.5 vs
    claude-opus-5-5) denotes the SAME model and is folded onto the existing
    block instead of being added as a twin. Dropping such a duplicate block
    is deduplication, not delisting — every distinct model is retained.
    """
    by_id = {b.get("id"): b for b in existing_blocks or [] if b.get("id")}
    by_canon = {}
    for bid, b in by_id.items():
        by_canon.setdefault(canonical_id(bid), b)
    out: List[Dict[str, Any]] = []
    seen = set()
    seen_canon = set()
    for b in new_blocks or []:
        mid = b.get("id")
        if not mid or mid in seen:
            continue
        c = canonical_id(mid)
        if c in seen_canon:
            continue  # twin spelling of a model already placed
        seen.add(mid)
        seen_canon.add(c)
        out.append(by_canon.get(c, b))
    for b in existing_blocks or []:
        mid = b.get("id")
        if not mid or mid in seen:
            continue
        c = canonical_id(mid)
        if c in seen_canon:
            continue  # twin spelling of the same model — fold, don't duplicate
        seen.add(mid)
        seen_canon.add(c)
        out.append(b)
    return out


def preserve_coding_plan_tiers(
    old_defaults: Dict[str, Any],
    selected: Dict[str, Optional[str]],
    merged_ids: set,
) -> Dict[str, Optional[str]]:
    """Keep a coding plan's hand-curated tier picks unless they broke.

    A tier is re-selected only when it is missing on disk or its model no
    longer exists in the merged catalog; a still-valid existing pick wins.
    """
    for tier in ("deep", "normal", "basic"):
        current = old_defaults.get(tier)
        if isinstance(current, str) and current in merged_ids:
            selected[tier] = current
        elif tier not in selected:
            selected[tier] = None
    return selected


def _extract_version(model_id: str) -> float:
    """First *version-like* number in the id: 3.8, 5.3, 4.7 ...

    Normalizes the two id conventions that fooled the naive regex:
    - Fireworks encodes the dot as "p" (qwen3p8-max, glm-5p3);
    - trailing date/snapshot suffixes are not versions (mistral-medium-2604
      = 2026-04, gpt-4o-2024-11-20, deepseek-v4.1-flash-1017) — a bare
      "11" from a date previously inflated the generational floor to 110.
    Parameter counts (816B, 235b, a95b) are rejected by the lookahead.
    """
    import re
    s = model_id.lower()
    s = re.sub(r'(\d)p(\d)', r'\1.\2', s)          # qwen3p8 -> qwen3.8
    s = re.sub(r'[-_.]\d{4,8}([-_.]\d{2}){0,2}$', '', s)  # strip -1017 / -2024-11-20 / -20241022
    s = re.sub(r'([-_.]\d{2}){1,3}$', '', s)       # strip MM leftovers: command-r7b-12-2024 -> command-r7b
    for match in re.finditer(r'(\d+)(?:\.(\d+))?(?![a-zA-Z0-9.])', s):
        major = int(match.group(1))
        if major > 20:
            continue  # year fragment (26.9 = 2026-09) or parameter count
        minor_s = match.group(2)
        # single-digit minor -> /10 (3.8 = 3+0.8); two-digit minor means a
        # dotted point release (4.20 = 4.2, 3.10 = 3.1), never +2.0
        minor = (int(minor_s) / (10 if len(minor_s) == 1 else 100)) if minor_s else 0.0
        return major + minor
    return 0.0


def _quality_rank(m: ModelInfo) -> float:
    """Single quality axis for tier ranking.

    The design_arena / artificial_analysis score stamped on cards is the
    factual capability measurement. Two guards keep feed gaps from
    inverting the order:

    - Generational floor: an unscored (or pathetically scored) model never
      ranks below its generation's proxy (major.minor * 10, +25 when it is
      a flagship of the current generation). Without this, a scored relic
      (gemma-2 at DA~20, or 2025-07 qwen-plus at ~55) outranked the
      unscored 2026-10 flagships (qwen3.8-max, gpt-6 family).
    - The floor uses the flagship TAG, which the sync itself stamps from
      the refreshed TAG_PATTERNS — no hand-maintained score table.
    """
    floor = _extract_version(m.id) * 10.0
    if 'flagship' in m.tags and 'legacy' not in m.tags:
        # 35 puts an unbenchmarked current-gen flagship above scored 2025
        # mid-tiers (e.g. qwen-plus-2025-07-28 at DA~64 vs qwen3.8-max) —
        # the whole point of the floor.
        floor += 35.0
    if m.score is not None:
        return max(float(m.score), floor)
    return floor


def _is_chat_model(m: ModelInfo) -> bool:
    mid = m.id.lower()
    if any(p in mid for p in NON_CHAT_ID_PATTERNS):
        return False
    # Cards registered from MDD descriptors carry their task kind (e.g.
    # MiniMax-H3 = video_generation): those never enter chat tiers either.
    return not any(t in ('video_generation', 'audio_generation', 'image_generation',
                         'audio_video', 'embedding') for t in (m.tags or []))


def _live_tags(model_id: str) -> List[str]:
    """Tags today's TAG_PATTERNS would stamp on this id."""
    mid = model_id.lower()
    out: List[str] = []
    for tag, patterns in TAG_PATTERNS.items():
        for pattern in patterns:
            if pattern in mid:
                if tag not in out:
                    out.append(tag)
                break
    return out


def _matches_family(m: ModelInfo, prefixes) -> bool:
    if not prefixes:
        return True
    mid = m.id.lower()
    return any(mid.startswith(p) for p in prefixes)


def select_tier_models_from_list(
    models: List[ModelInfo], limit: int = 3, is_coding_plan: bool = False,
    family_prefixes: Optional[tuple] = None,
) -> Dict[str, Optional[str]]:
    """Select N curated models from the list for each request tier.

    Audit 2026-10-21 rewrite — the old name-pattern sort produced tiers that
    contradicted the factual capability order (xai deep stayed on
    grok-4.20-0309-reasoning while grok-4.7 sat unused; deepseek deep was
    the old deepseek-reasoner alias; OpenAI normal was an *image* model;
    the Qwen entrypoint's tiers were all GLM/MiniMax). Ranking is now
    score-first (see _quality_rank) and candidates are restricted to the
    provider's own family (developer entrypoints), to chat-capable models,
    and to non-legacy/non-deprecated entries. A reasoning model still wins
    the deep tier unless a non-reasoning model outranks it by >=10 points
    (clearly the stronger model overall).

    For coding plans the per-model ``pricing`` field doubles as the plan's
    charge multiplier (1x = baseline). Only premium (>=1x) models belong in
    a plan; the basic tier requires a sub-1x model, which no premium plan
    model satisfies — so ``basic`` is left ``None`` and the runtime falls
    back to the normal-tier model for that provider.
    """
    pool = [
        m for m in models
        if 'legacy' not in m.tags and 'deprecated' not in m.tags
        and _is_chat_model(m) and _matches_family(m, family_prefixes)
    ]

    if is_coding_plan:
        pool = [m for m in pool if m.pricing_input >= 1.0]

    if not pool:
        # The family filter wiped everything (e.g. a provider whose whole
        # feed is third-party) — degrade to the unfiltered non-legacy list
        # instead of emitting empty tiers.
        pool = [m for m in models if 'legacy' not in m.tags and _is_chat_model(m)]

    pool.sort(key=lambda m: (-_quality_rank(m), m.id))

    # Deep tier: best reasoning model, unless a non-reasoning model is
    # clearly stronger overall (>=10 rank points).
    deep = None
    for m in pool:
        if m.supports_reasoning:
            deep = m
            break
    if pool:
        if deep is None or _quality_rank(pool[0]) - _quality_rank(deep) >= 10:
            deep = pool[0]

    # Normal tier: next-best everyday model — not the deep pick, not a
    # free/budget line; prefer the plain major-version base model (e.g.
    # "glm-5") over point releases (e.g. "glm-5.1"). Vision capability is
    # NOT an exclusion anymore: every 2026 frontier model is multimodal,
    # and the old rule dropped google/openai normals down to 2024 relics.
    def is_normal_candidate(m: ModelInfo) -> bool:
        if deep is not None and m.id == deep.id:
            return False
        if 'free' in m.tags:
            return False
        # Stale auto-tag compat (audit R2): TAG_PATTERNS dropped 'flash'
        # from cost_effective on 2026-10-21 (flash is the current-gen
        # MAINLINE mid tier at Google/Qwen/DeepSeek), but additive-only
        # sync leaves the old tag stamped on existing cards — which kept
        # every gemini flash out of the normal tier and left google
        # normal on gemma. Disk tags carry no provenance marker, so the
        # exclusion only bites when the id still matches a CURRENT
        # cost_effective pattern; genuine budget lines (mini/air/turbo/
        # lite) keep excluding as before.
        if 'cost_effective' in m.tags and 'cost_effective' in _live_tags(m.id):
            return False
        return True

    normal_candidates = [m for m in pool if is_normal_candidate(m)]
    if normal_candidates:
        import re as _re

        def is_plain_base(mid: str) -> bool:
            return bool(_re.fullmatch(r'[a-z]+-\d+', mid.lower()))

        plain_bases = [m for m in normal_candidates if is_plain_base(m.id)]
        normal = (plain_bases[0] if plain_bases else normal_candidates[0]).id
    else:
        others = [m for m in pool if deep is None or m.id != deep.id]
        normal = others[0].id if others else (deep.id if deep else None)

    # Basic tier: cheapest cost-effective line (price ASC, id as tiebreak).
    # A 0 input price here is a placeholder (feed gap or aggregator
    # stub like voxtral-mini-latest), not a real budget line — sorting
    # ASC would crown it — so only priced cards compete.
    if is_coding_plan:
        basic = None
    else:
        deep_id = deep.id if deep else None
        basic_pool = [
            m for m in pool
            if m.id not in (deep_id, normal) and m.pricing_input > 0
        ]
        tagged = [m for m in basic_pool if 'cost_effective' in m.tags or 'free' in m.tags]
        if tagged:
            basic = min(tagged, key=lambda m: (m.pricing_input, m.id)).id
        elif basic_pool:
            basic = min(basic_pool, key=lambda m: (m.pricing_input, m.id)).id
        else:
            basic = None

    return {
        'deep': deep.id if deep else None,
        'normal': normal,
        'basic': basic,
    }


def update_entrypoint_config(
    provider_id: str,
    entrypoint_file: str,
    models: List[ModelInfo],
    config_dir: Path,
    is_coding_plan: bool = False,
    update_defaults: bool = True,
) -> bool:
    """Update entrypoint config file"""
    is_coding_plan_entrypoint = any(x in entrypoint_file for x in ['coding_lite', 'coding_pro', 'coding_max'])

    cf.header(f"Updating Entrypoint: {provider_id}/{entrypoint_file}")
    if is_coding_plan_entrypoint:
        cf.info("Coding plan - selecting 3 models")

    # Developer entrypoints keep their tier defaults inside the provider's
    # own model family; platform entrypoints host everything (no filter).
    family_prefixes = None
    if provider_id not in PLATFORM_PROVIDERS:
        family_prefixes = PROVIDER_FAMILY_PREFIXES.get(provider_id)

    # Load existing config
    existing_config = load_entrypoint_config(provider_id, entrypoint_file, config_dir)
    if not existing_config:
        cf.warn("Config file does not exist, skipping")
        return False

    # Keep existing entrypoint config, only update models
    config = existing_config.copy()

    # For coding plans, limit models to a curated selection
    if is_coding_plan_entrypoint:
        # Select top models for each tier (coding plans restrict to ≥1x pool)
        selected = select_tier_models_from_list(
            models, limit=3, is_coding_plan=True, family_prefixes=family_prefixes
        )
        # Curation-first: a coding plan's tiers and charge multipliers are
        # hand-curated billing data — only re-select tiers that are missing
        # or whose model vanished from the merged catalog.
        old_def_defaults = (existing_config.get('entrypoint', {}) or {}).get('defaults') or {}
        selected = preserve_coding_plan_tiers(
            old_def_defaults, selected, {m.id for m in models}
        )
        # Get selected model objects
        selected_models = []
        for tier in ['deep', 'normal', 'basic']:
            model_id = selected.get(tier)
            if model_id:
                for m in models:
                    if m.id == model_id:
                        selected_models.append(m)
                        break

        # Remove duplicates while preserving order
        seen = set()
        unique_models = []
        for m in selected_models:
            if m.id not in seen:
                seen.add(m.id)
                unique_models.append(m)

        # Use simplified entrypoint format (only id + pricing); blocks for
        # returning ids keep their on-disk pricing (charge multipliers).
        new_blocks = [m.to_entrypoint_dict() for m in unique_models]
        old_blocks = (existing_config.get('entrypoint', {}) or {}).get('models') or []
        config['entrypoint']['models'] = curate_entrypoint_blocks(new_blocks, old_blocks)

        # Update defaults to match selected models
        if update_defaults and 'defaults' in config['entrypoint']:
            old_defaults = config['entrypoint']['defaults']
            preserved_keys = {
                k: v for k, v in old_defaults.items()
                if k not in ('deep', 'normal', 'basic')
            }
            # Drop None tiers (e.g. basic=None when no sub-1x model exists in
            # a coding plan) so the entrypoint simply omits that tier.
            clean_selected = {k: v for k, v in selected.items() if v is not None}
            config['entrypoint']['defaults'] = {**clean_selected, **preserved_keys}

        print(f"   Selected {len(unique_models)} models:")
        for m in unique_models:
            print(f"   - {m.id}: {m.name}")
    else:
        # For non-coding plans, include all models (up to 50)
        def model_sort_key(m: ModelInfo):
            has_recommended = 'recommended' in m.tags or 'flagship' in m.tags
            has_legacy = 'legacy' in m.tags
            return (not has_recommended, has_legacy, -m.pricing_input, m.name.lower())

        sorted_models = sorted(models, key=model_sort_key)

        # Deduplicate
        seen_ids = set()
        unique_models = []
        for model in sorted_models:
            if model.id not in seen_ids:
                seen_ids.add(model.id)
                unique_models.append(model)

        # Use simplified entrypoint format (only id + pricing). The cap
        # bounds NEW additions only — existing blocks are always retained
        # (curation-first; see curate_entrypoint_blocks).
        new_blocks = [m.to_entrypoint_dict() for m in unique_models[:50]]
        old_blocks = (existing_config.get('entrypoint', {}) or {}).get('models') or []
        config['entrypoint']['models'] = curate_entrypoint_blocks(new_blocks, old_blocks)

        print(f"   Updated {len(unique_models[:50])} models")

        # Update defaults
        if update_defaults:
            selected = select_tier_models_from_list(
                unique_models, limit=3, family_prefixes=family_prefixes
            )
            if 'defaults' in config['entrypoint']:
                old_defaults = config['entrypoint']['defaults']
                preserved_keys = {
                    k: v for k, v in old_defaults.items()
                    if k not in ('deep', 'normal', 'basic')
                }
                clean_selected = {k: v for k, v in selected.items() if v is not None}
                config['entrypoint']['defaults'] = {**clean_selected, **preserved_keys}

            cf.ok("Default models selected:")
            print(f"      Deep:   {selected.get('deep', 'N/A')}")
            print(f"      Normal: {selected.get('normal', 'N/A')}")
            print(f"      Basic:  {selected.get('basic', 'N/A')}")

    # Save
    save_entrypoint_config(provider_id, entrypoint_file, config, config_dir)
    return True


def update_provider_config(
    provider_id: str,
    models: List[ModelInfo],
    config_dir: Path,
    update_defaults: bool = False
) -> bool:
    """Update provider config file"""
    cf.header(f"Updating Provider: {provider_id}")

    if not update_defaults:
        cf.info("Skipping default model update (use --update-defaults to enable)")

    # Load existing config
    existing_config = load_existing_config(provider_id, config_dir)
    if not existing_config:
        cf.warn("Config file does not exist, skipping")
        return False

    # Keep existing provider config, only update models
    config = existing_config.copy()

    # Sort models: recommended/flagship first, then by version (newer first), then by name
    def extract_version(model_id: str) -> tuple:
        """Extract version tuple for sorting (higher versions first)"""
        import re
        # Match patterns like qwen3.5, gpt-5.4, glm-4.7
        match = re.search(r'(\d+)(?:\.(\d+))?', model_id)
        if match:
            major = int(match.group(1))
            minor = int(match.group(2)) if match.group(2) else 0
            return (major, minor)
        return (0, 0)

    def model_sort_key(m: ModelInfo):
        has_recommended = 'recommended' in m.tags or 'flagship' in m.tags
        has_legacy = 'legacy' in m.tags
        version = extract_version(m.id)
        # Sort: recommended first, then by version DESCENDING (newer first), then alphabetically
        return (not has_recommended, has_legacy, (-version[0], -version[1]), m.name.lower())

    sorted_models = sorted(models, key=model_sort_key)

    # Deduplicate by ID (keep first occurrence)
    seen_ids = set()
    unique_models = []
    for model in sorted_models:
        if model.id not in seen_ids:
            seen_ids.add(model.id)
            unique_models.append(model)

    # Convert to TOML format
    config['models'] = [m.to_toml_dict() for m in unique_models[:50]]  # Limit to 50 models

    print(f"   Updated {len(unique_models[:50])} models")
    for m in unique_models[:5]:
        print(f"   - {m.id}: {m.name}")

    # Update default models with smart selection (only if --update-defaults is set)
    if update_defaults and 'provider' in config:
        # Clean up any duplicate top-level defaults (keep only defaults.models)
        defaults = config['provider'].get('defaults', {})

        # Remove top-level tier keys if models sub-dict exists
        if 'models' in defaults:
            for tier in ['deep', 'normal', 'basic']:
                if tier in defaults and tier in defaults['models']:
                    del defaults[tier]  # Remove duplicate

        if 'models' not in defaults:
            defaults['models'] = {}

        cf.info("Using simple heuristic algorithm to select default models...")

        # Smart model selection for each tier
        reasoning_models = [m for m in unique_models if m.supports_reasoning and 'legacy' not in m.tags]
        coding_models = [m for m in unique_models if 'coding' in m.tags and 'legacy' not in m.tags]
        flagship_models = [m for m in unique_models if 'flagship' in m.tags and not m.supports_reasoning and 'legacy' not in m.tags]
        # Regular models: those without special tags (but not cost_effective only)
        regular_models = [m for m in unique_models if not m.supports_reasoning and 'legacy' not in m.tags
                        and 'flagship' not in m.tags and 'cost_effective' not in m.tags]
        basic_models = [m for m in unique_models if 'cost_effective' in m.tags]

        # Helper function to extract version number from model ID
        def extract_version_numeric(model_id: str) -> float:
            """Extract numeric version from model ID (e.g., m2.7 -> 2.7, m1 -> 1.0)"""
            import re
            # Match patterns like m2.7, m2.5, glm-4.7, gpt-5.4
            match = re.search(r'(\d+)(?:\.(\d+))?', model_id.lower())
            if match:
                major = float(match.group(1))
                minor = float(match.group(2)) if match.group(2) else 0.0
                return major + minor / 10.0
            return 0.0

        # Deep tier: reasoning models first, then flagship, then by version/price
        if reasoning_models:
            reasoning_models.sort(key=lambda m: m.pricing_input, reverse=True)
            defaults['models']['deep'] = reasoning_models[0].id
        elif flagship_models:
            flagship_models.sort(key=lambda m: m.pricing_input, reverse=True)
            defaults['models']['deep'] = flagship_models[0].id
        elif regular_models:
            regular_models.sort(key=lambda m: m.pricing_input, reverse=True)
            defaults['models']['deep'] = regular_models[0].id
        else:
            # Fallback: use cost_effective models, but pick by version and context
            # Prefer higher version numbers and larger context windows
            if basic_models:
                basic_models.sort(key=lambda m: (extract_version_numeric(m.id), m.context_window, m.pricing_input), reverse=True)
                defaults['models']['deep'] = basic_models[0].id

        # Normal tier: coding models first (for coding plans), then flagship, then balanced
        if coding_models:
            coding_models.sort(key=lambda m: m.pricing_input, reverse=True)
            defaults['models']['normal'] = coding_models[0].id
        elif flagship_models:
            flagship_models.sort(key=lambda m: m.pricing_input, reverse=True)
            defaults['models']['normal'] = flagship_models[0].id
        elif regular_models:
            regular_models.sort(key=lambda m: m.pricing_input, reverse=True)
            defaults['models']['normal'] = regular_models[0].id
        else:
            # Fallback: use cost_effective models with balanced performance
            # Prefer high version but not highest price (balanced tier)
            if basic_models:
                # Sort by version DESC, then by price ASC (prefer balanced options)
                balanced_models = sorted(basic_models,
                                       key=lambda m: (-extract_version_numeric(m.id), m.pricing_input))
                # Pick the second or third highest version for "normal" tier (balanced)
                if len(balanced_models) >= 2:
                    # For MiniMax: M2.7 is highest version, pick second highest or same version with lower price
                    defaults['models']['normal'] = balanced_models[1].id if balanced_models[1].pricing_input < balanced_models[0].pricing_input else balanced_models[0].id
                else:
                    defaults['models']['normal'] = balanced_models[0].id

        # Basic tier: cost-effective models (cheapest)
        if basic_models:
            basic_models.sort(key=lambda m: m.pricing_input)  # ASC for basic
            defaults['models']['basic'] = basic_models[0].id
        elif regular_models:
            # Fallback to cheapest regular model
            regular_models.sort(key=lambda m: m.pricing_input)
            defaults['models']['basic'] = regular_models[0].id if regular_models else None

        cf.ok("Default models selected:")
        print(f"      Deep:   {defaults['models'].get('deep', 'N/A')}")
        print(f"      Normal: {defaults['models'].get('normal', 'N/A')}")
        print(f"      Basic:  {defaults['models'].get('basic', 'N/A')}")

        config['provider']['defaults'] = defaults

    # Save
    save_config(provider_id, config, config_dir)
    return True


def load_existing_catalog(
    provider_id: str, config_dir: Path, include_entrypoint: bool = True
) -> Dict[str, ModelInfo]:
    """Existing cards for a provider in ONE canonical insertion order:
    entrypoint blocks first, then models/ dir cards.

    The order IS the spelling contract (audit R2): fold_by_canonical
    keeps the FIRST spelling it meets, and curate_entrypoint_blocks
    keeps the existing entrypoint block's spelling — building the
    existing dict entrypoint-first makes the fold winner and the
    emitted block id the SAME string, so tier defaults cannot dangle
    on a case variant of an emitted block (minimax normal flipped
    between "MiniMax-M3" and "minimax-m3" across runs before this).
    """
    existing: Dict[str, ModelInfo] = {}
    if include_entrypoint:
        for ep_provider, _ep_file, _desc in ENTRYPOINT_FILES:
            if ep_provider == provider_id:
                existing.update(
                    load_existing_models_from_entrypoint(provider_id, _ep_file, config_dir)
                )
                break
    existing.update(load_existing_models_from_dir(provider_id, config_dir))
    return existing


