# ------------------------------------------------------------
# Canonical id folding (audit 2026-10-21)
#
# The two feeds disagree on id spelling for the SAME model:
#   OpenRouter  anthropic/claude-haiku-5.5   (dot form)
#   models.dev  claude-haiku-5-5             (dash form, official API id)
#   OpenRouter  mistralai/mistral-large-4-0  vs models.dev mistral-large-4
#   models.dev  siliconflow listings: "deepseek-ai/DeepSeek-V4-Flash" and
#               "deepseek-ai_DeepSeek-V4-Flash" as separate ids
# Because the merge keys on the exact string and never deletes, every
# spelling disagreement minted a twin card + twin entrypoint block
# (24 normalized-twin groups were on disk by 2026-10-21). Folding keys on
# a separator/case-insensitive canonical form stops NEW twins from being
# minted; pre-existing twin files stay on disk (additive-only sync) until
# a curator consolidates them.
SEPARATOR_CHARS = "-._/"

# OpenRouter pins the first snapshot of a new major as "<id>-0" while the
# official API id (and models.dev) has no suffix: mistral-large-4-0 vs
# mistral-large-4, claude-opus-4-0 vs claude-opus-4, gpt-future-0 vs
# gpt-future. Fold exactly a word-char-anchored trailing "-0"; a real
# version like mistral-large-40 or a date like -0309 does not match.
import re as _re
_TRAILING_SNAPSHOT_ZERO = _re.compile(r'(\w)[-_.]0$')


def canonical_id(mid: str) -> str:
    """Case/separator-insensitive identity of a model id."""
    s = _TRAILING_SNAPSHOT_ZERO.sub(r'\1', mid.lower())
    return "".join(ch for ch in s if ch not in SEPARATOR_CHARS)


def fold_by_canonical(models: Dict[str, ModelInfo]) -> Dict[str, ModelInfo]:
    """Fold id spellings that differ only by case/separators into one card.

    The first spelling wins; a later twin only fills blanks on the kept
    card (curation-style), it never overwrites a meaningful value.
    """
    out: Dict[str, ModelInfo] = {}
    for mid, m in models.items():
        c = canonical_id(mid)
        for kept_id, kept in out.items():
            if canonical_id(kept_id) != c:
                continue
            if kept.pricing_input <= 0 and m.pricing_input > 0:
                kept.pricing_input = m.pricing_input
            if kept.pricing_output <= 0 and m.pricing_output > 0:
                kept.pricing_output = m.pricing_output
            if kept.pricing_cached <= 0 and m.pricing_cached > 0:
                kept.pricing_cached = m.pricing_cached
            if kept.context_window <= 0 and m.context_window > 0:
                kept.context_window = m.context_window
            if kept.max_output_tokens <= 0 and m.max_output_tokens > 0:
                kept.max_output_tokens = m.max_output_tokens
            if not kept.tags and m.tags:
                kept.tags = list(m.tags)
            if kept.score is None and m.score is not None:
                kept.score, kept.score_source = m.score, m.score_source
            if m.supports_reasoning and not kept.supports_reasoning:
                kept.supports_reasoning = True
            if m.supports_vision and not kept.supports_vision:
                kept.supports_vision = True
            break
        else:
            out[mid] = m
    return out


def rekey_onto_existing(
    feed: Dict[str, ModelInfo], existing: Dict[str, ModelInfo]
) -> Dict[str, ModelInfo]:
    """Rename feed ids to the spelling already on disk when they denote the
    same model, so curation-first matching sees one identity per model."""
    alias = {canonical_id(k): k for k in existing}
    out: Dict[str, ModelInfo] = {}
    for mid, m in feed.items():
        out[alias.get(canonical_id(mid), mid)] = m
    return out


def resolve_shared_new_ids(
    or_feed: Dict[str, ModelInfo],
    md_feed: Dict[str, ModelInfo],
    prefer_openrouter: bool,
) -> None:
    """For models NEW to the tree that both feeds carry under different
    spellings, rekey the non-preferred source onto the preferred spelling
    so the merge cannot mint a twin card.

    Call this after ``rekey_onto_existing``: by then, any divergence still
    left between the two feeds denotes a brand-new model. Spelling
    preference: the openrouter provider dir keeps OpenRouter ids (those are
    the routable ones there); every other provider prefers the models.dev
    spelling, which mirrors the provider's official API ids.
    """
    or_canon = {canonical_id(k): k for k in or_feed}
    for mid in list(md_feed):
        c = canonical_id(mid)
        or_key = or_canon.get(c)
        if or_key is None or or_key == mid:
            continue  # not shared, or already the same spelling
        if prefer_openrouter:
            md_feed[or_key] = md_feed.pop(mid)
        else:
            or_feed[mid] = or_feed.pop(or_key)


def merge_model_dicts(
    existing: Dict[str, ModelInfo],
    openrouter: Dict[str, ModelInfo],
    modelsdev: Dict[str, ModelInfo],
    aggregator_priority: bool = False,
) -> Dict[str, ModelInfo]:
    """Merge model data from multiple sources.

    Two precedence regimes share this merge:

    - Curation-first (the default): any field already on disk with a
      meaningful value (non-zero number, non-empty list, non-None score)
      WINS — the scheduled sync then only fills blanks and adds NEW
      models. Hand-verified official list prices (see PR #14) must never
      be clobbered by aggregator FX noise or stale mirrors.
    - Aggregator-priority (``--aggregator-priority``): the legacy regime
      (models.dev > OpenRouter > existing), for wholesale refreshes where
      the aggregator feeds are intentionally trusted over the tree.

    In both regimes, models absent from every source are kept unchanged.
    """
    priority = bool(aggregator_priority or AGGREGATOR_PRIORITY)

    def num(*cands):
        for v in cands:
            if v is not None and v > 0:
                return v
        return 0.0

    merged = {}

    all_ids = set()
    all_ids.update(existing.keys())
    all_ids.update(openrouter.keys())
    all_ids.update(modelsdev.keys())

    for model_id in sorted(all_ids):
        e = existing.get(model_id)
        o = openrouter.get(model_id)
        m = modelsdev.get(model_id)

        if priority or e is None:
            # Legacy regime, and the stamping path for models new to the
            # tree (no on-disk card to curate).
            if m:
                base = m
            elif o:
                base = o
            else:
                base = e

            if base is None:
                continue

            merged[model_id] = ModelInfo(
                id=model_id,
                name=base.name,
                context_window=base.context_window,
                max_output_tokens=base.max_output_tokens,
                supports_vision=base.supports_vision,
                supports_function_calling=base.supports_function_calling,
                supports_streaming=base.supports_streaming,
                supports_reasoning=base.supports_reasoning,
                tags=base.tags,
                pricing_input=base.pricing_input,
                pricing_output=base.pricing_output,
                pricing_cached=base.pricing_cached,
                score=base.score,
                score_source=base.score_source,
            )

            if m:
                # models.dev has priority, but it sometimes omits pricing/context
                # (returns 0) for newly-listed models. Don't let those placeholder
                # zeros clobber the real OpenRouter values — fall back to OpenRouter
                # for any field models.dev reports as 0.
                if m.pricing_input > 0 or o is None or o.pricing_input <= 0:
                    merged[model_id].pricing_input = m.pricing_input
                else:
                    merged[model_id].pricing_input = o.pricing_input
                if m.pricing_output > 0 or o is None or o.pricing_output <= 0:
                    merged[model_id].pricing_output = m.pricing_output
                else:
                    merged[model_id].pricing_output = o.pricing_output
                if m.pricing_cached > 0:
                    merged[model_id].pricing_cached = m.pricing_cached
                elif o is not None:
                    merged[model_id].pricing_cached = o.pricing_cached
                if m.context_window > 0:
                    merged[model_id].context_window = m.context_window
                elif o is not None and o.context_window > 0:
                    merged[model_id].context_window = o.context_window
                if m.max_output_tokens > 0:
                    merged[model_id].max_output_tokens = m.max_output_tokens
                elif o is not None and o.max_output_tokens > 0:
                    merged[model_id].max_output_tokens = o.max_output_tokens
                merged[model_id].supports_vision = m.supports_vision
                merged[model_id].supports_reasoning = m.supports_reasoning
                merged[model_id].supports_function_calling = m.supports_function_calling
            elif o:
                if o.pricing_input > 0:
                    merged[model_id].pricing_input = o.pricing_input
                if o.pricing_output > 0:
                    merged[model_id].pricing_output = o.pricing_output
                if o.pricing_cached > 0:
                    merged[model_id].pricing_cached = o.pricing_cached
                if e is None or e.context_window == 128000:
                    merged[model_id].context_window = o.context_window

            # Score merge: live OpenRouter benchmarks win; otherwise preserve any
            # score already on disk (covers manual overrides and models absent from
            # the live API). models.dev carries no benchmark data.
            if o is not None and o.score is not None:
                merged[model_id].score = o.score
                merged[model_id].score_source = o.score_source
            elif e is not None and e.score is not None:
                merged[model_id].score = e.score
                merged[model_id].score_source = e.score_source
            continue

        # Curation-first: the on-disk card is authoritative; aggregator
        # sources only fill blanks (zeroed pricing/context, missing score
        # or tags).
        card = ModelInfo(
            id=e.id,
            name=e.name,
            context_window=e.context_window,
            max_output_tokens=e.max_output_tokens,
            supports_vision=e.supports_vision,
            supports_function_calling=e.supports_function_calling,
            supports_streaming=e.supports_streaming,
            supports_reasoning=e.supports_reasoning,
            tags=list(e.tags),
            pricing_input=e.pricing_input,
            pricing_output=e.pricing_output,
            pricing_cached=e.pricing_cached,
            score=e.score,
            score_source=e.score_source,
        )
        if card.pricing_input <= 0:
            card.pricing_input = num(m and m.pricing_input, o and o.pricing_input)
        if card.pricing_output <= 0:
            card.pricing_output = num(m and m.pricing_output, o and o.pricing_output)
        if card.pricing_cached <= 0:
            card.pricing_cached = num(m and m.pricing_cached, o and o.pricing_cached)
        if card.context_window <= 0:
            card.context_window = int(num(m and m.context_window, o and o.context_window)) or card.context_window
        if card.max_output_tokens <= 0:
            card.max_output_tokens = int(num(m and m.max_output_tokens, o and o.max_output_tokens)) or card.max_output_tokens
        if not card.tags:
            card.tags = list((m.tags if m and m.tags else (o.tags if o and o.tags else [])) or [])
        if card.score is None:
            if o is not None and o.score is not None:
                card.score = o.score
                card.score_source = o.score_source
        merged[model_id] = card

    return merged


def load_existing_models_from_entrypoint(
    provider_id: str, entrypoint_file: str, config_dir: Path
) -> Dict[str, ModelInfo]:
    """Load model list from existing entrypoint file"""
    config = load_entrypoint_config(provider_id, entrypoint_file, config_dir)
    if not config:
        return {}

    result = {}
    models = config.get('entrypoint', {}).get('models', [])
    for m in models:
        mid = m.get('id', '')
        if not mid:
            continue
        pricing = m.get('pricing', {})
        result[mid] = ModelInfo(
            id=mid,
            name=mid,
            context_window=0,
            max_output_tokens=0,
            pricing_input=pricing.get('input_per_million', 0),
            pricing_output=pricing.get('output_per_million', 0),
            pricing_cached=pricing.get('cached_per_million', 0),
        )
    return result


def load_existing_models_from_dir(
    provider_id: str, config_dir: Path
) -> Dict[str, ModelInfo]:
    """Load existing model files from models/ directory"""
    models_dir = config_dir / "models" / provider_id
    if not models_dir.exists():
        return {}

    import toml  # type: ignore[import-untyped]
    result = {}
    for toml_file in sorted(models_dir.glob("*.toml")):
        try:
            with open(toml_file, 'r', encoding='utf-8') as f:
                data = toml.load(f)
            model = data.get('model', {})
            mid = model.get('id', '')
            if not mid:
                continue
            pricing = model.get('pricing', {})
            tags = model.get('tags', [])
            score_block = model.get('score', {}) or {}
            result[mid] = ModelInfo(
                id=mid,
                name=model.get('name', mid),
                context_window=model.get('context_window', 0),
                max_output_tokens=model.get('max_output_tokens', 0),
                supports_vision=model.get('supports_vision', False),
                supports_function_calling=model.get('supports_function_calling', True),
                supports_streaming=model.get('supports_streaming', True),
                supports_reasoning=model.get('supports_reasoning', False),
                tags=tags if tags else [],
                pricing_input=pricing.get('input_per_million', 0),
                pricing_output=pricing.get('output_per_million', 0),
                pricing_cached=pricing.get('cached_per_million', 0),
                score=score_block.get('value'),
                score_source=score_block.get('source', ''),
            )
        except Exception:
            continue
    return result


