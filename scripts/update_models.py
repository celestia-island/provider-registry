# Capability score normalization.
#
# OpenRouter exposes two benchmark suppliers under `benchmarks`:
#   - `artificial_analysis`: normalized indices ~0-100 (coding_index /
#     intelligence_index / agentic_index). Covers fewer models.
#   - `design_arena`: list of per-category Elo ratings (~1000-1400). Covers
#     most models and is the primary source used here.
#
# To make the two suppliers comparable on a single axis we map the
# design_arena mean Elo onto the artificial_analysis index scale using a
# linear fit (index = SLOPE*elo + INTERCEPT) derived from the 36 models that
# carry BOTH suppliers. The coefficients are a constant snapshot; they can be
# regenerated by refitting against the live data, but a stable mapping keeps
# scores deterministic across sync runs.
SCORE_ELO_SLOPE = 0.1463
SCORE_ELO_INTERCEPT = -124.3


def compute_score_from_benchmarks(benchmarks: Dict) -> Tuple[Optional[float], str]:
    """Compute a single normalized capability score from benchmark data.

    Priority: design_arena mean Elo (mapped) > artificial_analysis index.
    Returns (score, source); (None, "") when no benchmark data is available.
    """
    da = benchmarks.get('design_arena') or []
    elos = [x.get('elo') for x in da if isinstance(x, dict) and x.get('elo')]
    if elos:
        mapped = SCORE_ELO_SLOPE * (sum(elos) / len(elos)) + SCORE_ELO_INTERCEPT
        return round(mapped, 2), 'design_arena'

    aa = benchmarks.get('artificial_analysis') or {}
    idx = aa.get('coding_index') or aa.get('intelligence_index') or aa.get('agentic_index')
    if idx is not None:
        return round(float(idx), 2), 'artificial_analysis'

    return None, ""

